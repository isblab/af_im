"""
This module contains wrapper classes for using MolProbity.
Run MolProbity and provide the validation output.
"""
from typing import List, Tuple, Dict
import os, shutil
from multiprocessing import Pool

from utils.utils import run_subprocess


class Molprobity():
	"""
	Perform Molprobity validation on the set of input models.
	"""
	def __init__(
		self,
		model_ids: List[int],
		model_files: List[str],
		tmp_dir_path: str
	):
		self.model_ids = model_ids
		self.model_files = model_files
		self.tmp_dir_path = tmp_dir_path

		self.molprob_dict = {}


	def forward( self ):
		"""
		"""
		self.create_tmp_dir()
		self.run_molprobity_in_parallel()
		self.remove_tmp_dir()


	def create_tmp_dir( self ):
		"""
		Temporary directory is used for storing the intermediate files
			from running Molprobity validation.
		"""
		os.makedirs( self.tmp_dir_path, exist_ok = True )


	def remove_tmp_dir( self ):
		shutil.rmtree( self.tmp_dir_path )
		# cmd = ["rm", "-r", f"{self.tmp_dir}"]
		# run_subprocess( command = cmd )

	################################################################################
	################################################################################
	def run_molprobity_in_parallel( self ):
		"""
		Perfom Molprobity validation on the given set of models in parallel.
		"""
		models = zip( self.model_ids, self.model_files )
		with Pool( self.cores ) as p:
			for result in p.imap_unordered( self.validate, models ):
				self.molprob_dict.update( result )


	def validate( self,
		models: Tuple[int, str]
	) -> Dict[int, Dict[str, float]]:
		"""
		Perform Molprobity validation.
		Get the Molprobity metrics.
		"""
		model_id, model_file = models
		output_dir = os.path.join( self.tmp_dir, f"model_{model_id}" )

		summary_dict = self.run_molprobity( model_file = model_file,
							output_dir = output_dir )		
		return {model_id: summary_dict}


	def run_molprobity( self, model_file: str, output_dir: str ):
		"""
		Run Molprobity validation using Phenix.
		requires a PDB file with just 1 model.
		Generates the following files:
			{prefix}_coot.py  {prefix}.out  {prefix}.pkl  {prefix}.txt

		output_dir --> must be in the format "/path/prefix".
			where path is the output directory path and prefix is the 
				name for the output files generated.
		"""
		molprob_cmd = [
						"phenix.molprobity",
						f"{model_file}",
						f"output.prefix={output_dir}"
						]

		run_subprocess( command = molprob_cmd )
		summary_dict = self.get_molprobity_validation_summary(
			output_dir = output_dir
		)
		return summary_dict


	def get_molprobity_validation_summary( self, output_dir: str
										) -> Dict[str, float]:
		"""
		Molprobity can provide detailed information about:
			Ramachandran outliers
						favored
			Rotamer outliers
			C-beta deviations
			Clashscore
			RMS(bonds)
			RMS(angles)
			MolProbity score
			Resolution
			R-work
			R-free
			Refinement program
		All this can be obtained from the *.out file generated by molprobity.
		"""
		with open( f"{output_dir}.out", "r" ) as f:
			summary = f.readlines()

		summary_dict = {}
		for i in range( len( summary ) ):
			line = summary[i]
			if "Summary" in line:
				for j in range( i+1, len( summary ) ):
					l = summary[j]

					split_line = l.strip().split( " = " )
					if len( split_line ) < 2:
						continue

					key, value = split_line 
					key = "".join( key.split( "  " ) )
					value = "".join( value.split( "  " ) )

					# Remove spaces from the end.
					key = key[:-1] if key[-1] == " " else key
					# Remove '%' symbols.
					value = value.replace( "%", "" )
					
					if value.isalpha():
						summary_dict[key] = value
					else:
						summary_dict[key] = float( value )

		return summary_dict
